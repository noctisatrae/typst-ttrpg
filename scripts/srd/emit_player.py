# Part of scripts/srd (see README.md).
# Typst emitters for the records of player.py. Text goes into Typst string
# literals, so no SRD wording can be read as markup; bullet lists become
# Typst lists. Feature effects come from the hand-curated overlay
# (packages/daggerheart-srd/src/effects.typ) through `fx(kind, id, name)`.
from emit import lit, option_lines, slug
import structure

HEADER = """// {title}, transcribed from the Daggerheart SRD 2.0
// (DH_SRD_2_2026_08_25.pdf). Public Game Content © Critical Role, LLC,
// used under the Darrington Press Community Gaming License; see NOTICE.md.
//
// GENERATED by scripts/srd/build.py: do not edit; fix the parser or the
// effects overlay (effects.typ) and rebuild. Text is verbatim except: line
// breaks joined; the SRD's inline emphasis is not reproduced. ids are the
// kebab-case of the name. `flags.source.page` is the SRD page.

#import "@local/heartweaver:0.1.0": {imports}
#import "../effects.typ": fx

#let source(page) = (source: (document: "Daggerheart SRD", version: "2.0", page: page))
"""


def ident(name):
    s = slug(name)
    return s if not s[0].isdigit() else 'n-' + s


def body(blocks, indent=4):
    """A string literal for one paragraph, else a content block."""
    if not blocks:
        return '""'
    if len(blocks) == 1 and 'text' in blocks[0] and not structure.options(blocks[0]['text']):
        return lit(blocks[0]['text'])
    pad = ' ' * indent
    lines = ['[']
    for i, b in enumerate(blocks):
        if i:
            lines.append('')
        if 'text' in b:
            lines += option_lines(b['text'], pad)
        else:
            lines += [pad + '  - #' + lit(x) for x in b['bullets']]
    lines.append(pad + ']')
    return '\n'.join(lines)


def feature(kind, owner, f, indent=4):
    pad = ' ' * indent
    return f'{pad}feature({lit(f["name"])}, {body(f["body"], indent)}, ..fx({lit(kind)}, {lit(owner)}, {lit(f["name"])})),'


def features(kind, owner, fs, indent=4):
    if not fs:
        return '()'
    return '(\n' + '\n'.join(feature(kind, owner, f, indent + 2) for f in fs) + '\n' + ' ' * indent + ')'


def entries(names):
    return '\n/// Every entry in this file, in SRD order.\n#let entries = (' + ', '.join(names) + ',)\n'


def classes(cls, subs):
    out = [HEADER.format(title='Classes and subclasses', imports='class, subclass, feature')]
    names = []
    for c in cls:
        n = ident(c['name'])
        names.append(n)
        out.append(f'#let {n} = class(')
        out.append(f'  id: {lit(slug(c["name"]))},')
        out.append(f'  name: {lit(c["name"])},')
        out.append(f'  description: {lit(c["description"])},')
        out.append('  domains: (' + ', '.join(lit(d) for d in c['domains']) + ',),')
        out.append(f'  evasion: {c["evasion"]},')
        out.append(f'  hp: {c["hp"]},')
        out.append(f'  items: {lit(c["items"])},')
        hf = c['hope-feature']
        out.append(f'  hope-feature: feature({lit(hf["name"])}, {body(hf["body"], 2)}, ..fx("class", {lit(slug(c["name"]))}, {lit(hf["name"])})),')
        out.append(f'  features: {features("class", slug(c["name"]), c["features"], 2)},')
        out.append('  background-questions: (' + ''.join('\n    ' + lit(q) + ',' for q in c['background-questions']) + '\n  ),')
        out.append('  connections: (' + ''.join('\n    ' + lit(q) + ',' for q in c['connections']) + '\n  ),')
        out.append(f'  flags: source({c["page"]}),')
        out.append(')\n')
    for s in subs:
        n = ident(s['name'])
        names.append(n)
        sid = slug(s['name'])
        out.append(f'#let {n} = subclass(')
        out.append(f'  id: {lit(sid)},')
        out.append(f'  name: {lit(s["name"])},')
        out.append(f'  description: {lit(s["description"])},')
        out.append(f'  class: {lit(slug(s["class"]))},')
        if s['spellcast-trait']:
            out.append(f'  spellcast-trait: {lit(s["spellcast-trait"])},')
        for step in ('foundation', 'specialization', 'mastery'):
            out.append(f'  {step}: {features("subclass", sid, s[step], 2)},')
        out.append(f'  flags: source({s["page"]}),')
        out.append(')\n')
    return '\n'.join(out) + entries(names)


def heritage(records, kind):
    title = {'ancestry': 'Ancestries', 'community': 'Communities'}[kind]
    out = [HEADER.format(title=title, imports=f'{kind}, feature')]
    names = []
    for r in records:
        n = ident(r['name'])
        names.append(n)
        out.append(f'#let {n} = {kind}(')
        out.append(f'  id: {lit(slug(r["name"]))},')
        out.append(f'  name: {lit(r["name"])},')
        out.append(f'  description: {lit(r["description"])},')
        out.append(f'  features: {features(kind, slug(r["name"]), r["features"], 2)},')
        out.append(f'  flags: source({r["page"]}),')
        out.append(')\n')
    return '\n'.join(out) + entries(names)


def cards(records):
    out = [HEADER.format(title='Domain cards', imports='domain-card, feature')]
    names = []
    for r in records:
        n = ident(r['name'])
        names.append(n)
        cid = slug(r['name'])
        out.append(f'#let {n} = domain-card(')
        out.append(f'  id: {lit(cid)}, name: {lit(r["name"])},')
        out.append(f'  domain: {lit(r["domain"])}, level: {r["level"]}, type: {lit(r["type"])}, recall-cost: {r["recall-cost"]},')
        if r['text']:
            out.append(f'  text: {body(r["text"], 2)},')
            if not r['features']:
                out.append(f'  ..fx("domain-card", {lit(cid)}, {lit(r["name"])}),')
        if r['features']:
            out.append(f'  features: {features("domain-card", cid, r["features"], 2)},')
        out.append(f'  flags: source({r["page"]}),')
        out.append(')\n')
    return '\n'.join(out) + entries(names)


def weapons(records, title='Weapons and combat wheelchairs', tags=()):
    out = [HEADER.format(title=title, imports='weapon, feature')]
    names = []
    for r in records:
        n = ident(r['name'])
        names.append(n)
        wid = slug(r['name'])
        out.append(f'#let {n} = weapon(')
        out.append(f'  id: {lit(wid)}, name: {lit(r["name"])}, tier: {r["tier"]}, category: {lit(r["category"])},')
        out.append(f'  trait: {lit(r["trait"])}, range: {lit(r["range"])}, damage: {lit(r["damage"])}, damage-type: {lit(r["damage-type"])},')
        out.append(f'  burden: {lit(r["burden"])},')
        if r.get('frame'):
            out.append(f'  tags: ("combat-wheelchair", {lit(r["frame"] + "-frame")}),')
        elif tags:
            out.append('  tags: (' + ', '.join(lit(t) for t in tags) + ',),')
        if r['feature']:
            f = {'name': r['feature'], 'body': [{'text': r['feature-text']}] if r['feature-text'] else []}
            out.append(f'  features: ({feature("weapon", wid, f, 0).strip()}),')
        out.append(f'  flags: source({r["page"]}),')
        out.append(')\n')
    return '\n'.join(out) + entries(names)


